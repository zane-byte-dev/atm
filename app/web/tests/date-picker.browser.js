async (page) => {
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('http://127.0.0.1:5173/tests/fixtures/task-controls.html')
  await page.getByRole('button', { name: '筛选', exact: true }).click()
  await page.getByRole('menuitem', { name: '创建日期', exact: true }).click()
  const start = page.getByRole('textbox', { name: '开始日期', exact: true })
  await start.click()
  const popup = page.locator('.ant-picker-dropdown:not(.ant-picker-dropdown-hidden):not([class*="-leave"])').last()
  await popup.waitFor()
  check(await page.locator('input[type="date"]').count() === 0, 'Native date control remains')
  await start.fill('2026-10-03')
  await start.press('Enter')
  check((await page.locator('output[aria-label="当前配置"]').textContent()).includes('from=2026-10-03'), 'Start date format lost')
  const end = page.getByRole('textbox', { name: '结束日期', exact: true })
  await end.click()
  await popup.waitFor()
  check(await popup.locator('td[title="2026-10-02"]').evaluate(el => el.className.includes('disabled')), 'Date order bound missing')
  await end.fill('2026-10-08')
  await end.press('Enter')
  check((await page.locator('output[aria-label="当前配置"]').textContent()).includes('to=2026-10-08'), 'End date lost')
  await page.getByRole('button', { name: '清除日期', exact: true }).click()
  check(!(await page.locator('output[aria-label="当前配置"]').textContent()).includes('from='), 'Clear failed')
  await page.setViewportSize({ width: 390, height: 844 })
  await start.click()
  await popup.waitFor()
  await page.waitForFunction(() => { const e=document.querySelector('.ant-picker-dropdown:not(.ant-picker-dropdown-hidden):not([class*="-leave"])'); if(!e)return false; const r=e.getBoundingClientRect(); return r.left>=0 && r.right<=innerWidth })
  await page.waitForFunction(() => Array.from(document.querySelectorAll('.ant-picker-dropdown')).every(el => !el.className.includes('-appear') && !el.className.includes('-enter')))
  check(await popup.evaluate(el => { const r=el.getBoundingClientRect(); return r.left>=0 && r.right<=innerWidth }), 'Mobile calendar outside viewport')
  await page.screenshot({ path: '/private/tmp/atm-antd-date-picker.png' })
  return 'PASS: Ant Design calendar, ISO local dates, range bounds, clear and narrow popup'
}
