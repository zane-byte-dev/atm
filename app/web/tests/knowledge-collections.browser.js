async (page) => {
 const check = (value, message) => { if (!value) throw new Error(message) }
 const url = 'http://127.0.0.1:5173/tests/fixtures/knowledge-collections.html'
 await page.setViewportSize({width:1280,height:900})
 await page.goto(url)
 await page.evaluate(() => localStorage.removeItem('atm.web.native-preferences.v1'))
 await page.reload()
 await page.getByRole('button', {name:'集合管理',exact:true}).click()
 const dialog = page.getByRole('dialog', {name:'集合管理'})
 const ids = () => dialog.locator('[data-collection-id]').evaluateAll(rows => rows.map(row => row.dataset.collectionId).join(','))
 check(await ids() === 'notes,reference,empty','initial order')
 await dialog.getByRole('button',{name:'拖动工程笔记',exact:true}).dragTo(dialog.locator('[data-collection-id="empty"]'))
 check(await ids() === 'reference,empty,notes','drag reorder failed')
 await dialog.getByRole('button',{name:'上移工程笔记',exact:true}).click()
 check(await ids() === 'reference,notes,empty','button reorder failed')
 await page.reload()
 await page.getByRole('button', {name:'集合管理',exact:true}).click()
 check(await ids() === 'reference,notes,empty','order not persisted')
 await dialog.getByRole('button',{name:'编辑工程笔记',exact:true}).click()
 await dialog.getByRole('textbox',{name:'集合名称',exact:true}).fill('error')
 await dialog.getByRole('button',{name:'保存',exact:true}).click()
 await dialog.getByText('模拟保存失败，请重试',{exact:true}).waitFor()
 await dialog.getByRole('textbox',{name:'集合名称',exact:true}).fill('团队知识')
 await dialog.getByRole('textbox',{name:'集合说明',exact:true}).fill('共享的组件与接口约定')
 await dialog.getByRole('button',{name:'保存',exact:true}).click()
 await dialog.getByText('集合信息已保存。',{exact:true}).waitFor()
 await page.getByRole('button',{name:'拖动团队知识',exact:true}).first().waitFor()
 await dialog.getByRole('button',{name:'删除团队知识',exact:true}).click()
 check(await dialog.getByRole('button',{name:'移动文档并删除集合',exact:true}).isDisabled(),'nonempty delete enabled without target')
 await dialog.getByRole('combobox',{name:'接收集合',exact:true}).click()
 await page.locator('.ant-select-item-option[title="参考资料"]').click()
 await dialog.getByRole('button',{name:'移动文档并删除集合',exact:true}).click()
 await dialog.getByText('文档已移动，集合已删除。',{exact:true}).waitFor()
 check(await ids() === 'reference,empty','deleted collection remains')
 check(await dialog.locator('[data-collection-id="reference"]').textContent().then(t=>t.includes('3 篇文档')),'documents not moved')
 await dialog.getByRole('button',{name:'删除待整理',exact:true}).click()
 await dialog.getByRole('button',{name:'取消',exact:true}).click()
 check(await ids() === 'reference,empty','cancel deleted collection')
 await dialog.getByRole('button',{name:'删除待整理',exact:true}).click()
 await dialog.getByRole('button',{name:'确认删除空集合',exact:true}).click()
 await dialog.getByText('空集合已删除。',{exact:true}).waitFor()
 check(await ids() === 'reference','empty delete failed')
 check(await page.evaluate(()=>window.collectionRequests.filter(r=>r.method==='knowledge.collection.delete').every(r=>!('force' in r.input))),'force sent')
 await page.screenshot({path:'/private/tmp/atm-collections-desktop.png'})
 // Test sidebar drag and mobile keyboard alternative in a fresh fixture.
 await page.goto(url)
 await page.getByRole('button',{name:'拖动待整理',exact:true}).dragTo(page.getByRole('button',{name:'拖动参考资料',exact:true}))
 await page.getByRole('button', {name:'集合管理',exact:true}).click()
 check((await ids()).startsWith('empty,'),'sidebar order not shared with manager')
 await dialog.getByRole('button',{name:'关闭',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button', {name:'集合管理',exact:true}).click()
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile overflow')
 await dialog.getByRole('button',{name:'编辑工程笔记',exact:true}).click()
 await page.waitForFunction(() => !document.querySelector('.ant-modal[class*="ant-zoom"]'))
 const box = await dialog.boundingBox()
 check(box.x >= 0 && box.x + box.width <= 391, 'mobile dialog outside viewport')
 await page.screenshot({path:'/private/tmp/atm-collections-mobile.png'})
 await page.goto(url+'?readonly')
 await page.getByRole('button', {name:'集合管理',exact:true}).click()
 check(await dialog.getByRole('button',{name:/编辑|删除/}).count() === 0,'readonly mutation controls shown')
 check(await dialog.getByRole('button',{name:'下移待整理',exact:true}).isEnabled(),'readonly local order disabled')
 // Storage rejection must leave the visible order unchanged and recover on retry.
 const beforeFailure = await ids()
 await page.evaluate(() => {
   window.originalStorageSet = Storage.prototype.setItem
   Storage.prototype.setItem = function (key, value) {
     if (key === 'atm.web.native-preferences.v1') throw new DOMException('blocked', 'SecurityError')
     return window.originalStorageSet.call(this, key, value)
   }
 })
 await dialog.getByRole('button',{name:'下移待整理',exact:true}).click()
 await dialog.getByText('无法保存集合排序，请允许浏览器本地存储后重试。',{exact:true}).waitFor()
 check(await ids() === beforeFailure, 'failed storage changed visible order')
 await page.evaluate(() => { Storage.prototype.setItem = window.originalStorageSet })
 await dialog.getByRole('button',{name:'下移待整理',exact:true}).click()
 check(await ids() !== beforeFailure, 'storage retry did not recover')
 return 'PASS: manager/sidebar drag, keyboard ordering, persisted order, rename retry, safe move/delete/cancel, mobile, readonly, storage failure/retry'
}
