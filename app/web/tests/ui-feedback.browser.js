// Every operation uses fixture data.
async (page) => {
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  const fixture = 'http://127.0.0.1:5173/tests/fixtures/workspace-layout.html'
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto(`${fixture}?scene=agents`)
  await page.getByRole('button', { name: /核对工作区布局/ }).waitFor()
  check(await page.locator('.activity-index-row, .agent-filter-bar, .activity-run-overview').count() === 0, 'Agent diagnostic chrome remains')
  await page.getByRole('button', { name: '筛选会话', exact: true }).click()
  await page.getByRole('region', { name: '会话筛选' }).waitFor()
  await page.getByRole('button', { name: '收起筛选' }).click()
  await page.getByRole('button', { name: /核对工作区布局/ }).click()
  await page.getByRole('heading', { name: '核对工作区布局', level: 2 }).waitFor()
  check(await page.getByText('三栏是否对齐？').isVisible(), 'Conversation question missing')
  check(await page.getByText('列宽和内容起点已统一。').isVisible(), 'Conversation answer missing')
  await page.getByRole('button', { name: '会话信息', exact: true }).click()
  await page.getByText('s1', { exact: true }).waitFor()
  await page.getByRole('heading', { name: '核对工作区布局', level: 2 }).click()
  const rail = page.getByRole('navigation', { name: '主导航' })
  for (const name of ['ToDo', '知识库', '设置']) {
    await rail.getByRole('link', { name, exact: true }).hover()
    const tooltip = page.getByRole('tooltip', { name, exact: true })
    await tooltip.waitFor()
    check(await tooltip.evaluate((element) => {
      const r = element.getBoundingClientRect()
      const hit = document.elementFromPoint(r.left + r.width / 2, r.top + r.height / 2)
      return !!hit && element.contains(hit) && !element.closest('.workspace-rail')
    }), `${name} tooltip covered`)
  }
  await page.goto(`${fixture}?scene=knowledge&interactive=1&collection=test&document=doc1`)
  await page.getByRole('heading', { name: '布局记录', exact: true }).waitFor()
  const branch = page.locator('.knowledge-branch').last()
  const actions = branch.locator('.knowledge-branch-actions')
  await page.mouse.move(0, 0)
  check(!await actions.isVisible(), 'Selection displayed actions')
  const before = await branch.locator('.knowledge-branch-title').boundingBox()
  const countLeft = await branch.locator('.knowledge-branch-count').evaluate(el => el.getBoundingClientRect().left)
  await branch.locator('.knowledge-branch-heading').hover()
  check(await actions.isVisible(), 'Hover actions missing')
  check(await branch.locator('.knowledge-branch-count').evaluate(el => getComputedStyle(el).visibility === 'hidden'), 'Count remains under actions')
  const after = await branch.locator('.knowledge-branch-title').boundingBox()
  check(before.width === after.width, 'Actions reserve width')
  await page.mouse.move(0, 0)
  check(!await actions.isVisible(), 'Actions persisted after hover')
  const counterFrames = await branch.locator('.knowledge-branch-count').evaluate(async el => {
    const positions = []
    for(let frame=0; frame<6; frame++) { positions.push(el.getBoundingClientRect().left); await new Promise(resolve => requestAnimationFrame(resolve)) }
    return positions
  })
  check(counterFrames.every(left => Math.abs(left - countLeft) < 0.5), 'Collection counter slides after hover')
  await page.goto(`${fixture}?scene=usage&view=quota&interactive=1`)
  await page.getByRole('button', { name: '刷新实时额度', exact: true }).waitFor()
  await page.evaluate(() => localStorage.removeItem('atm.web.notifications.v1'))
  await page.reload()
  await page.getByRole('button', { name: '刷新实时额度', exact: true }).click()
  await page.getByText('刷新实时额度 · 排队中', { exact: true }).waitFor()
  check(await page.locator('.usage-detail .workspace-job').count() === 0, 'Inline completion card remains')
  await rail.getByRole('link', { name: '消息', exact: true }).click()
  await page.getByText('刷新实时额度 · 已完成', { exact: true }).first().waitFor({ timeout: 10000 })
  check(await page.locator('.ant-notification-notice').count() === 1, 'Duplicate notifications')
  check(await page.locator('.messages-list .workspace-list-item').count() === 1, 'Duplicate job history')
  await page.locator('.messages-list .workspace-list-item').click()
  check(await page.getByText('未读 0', { exact: true }).isVisible(), 'Read state missing')
  await page.goto(`${fixture}?scene=messages&interactive=1`)
  await page.getByText('没有未读消息', { exact: true }).waitFor()
  await page.getByText('全部 1', { exact: true }).click()
  await page.locator('.messages-list .workspace-list-item').waitFor()
  check(await page.locator('.messages-list .workspace-list-item-unread').count() === 0, 'Read state lost')
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Messages overflow')
  await page.goto(`${fixture}?scene=usage&view=quota&interactive=1&failJob=1`)
  await page.getByRole('button', { name: '刷新实时额度', exact: true }).click()
  await page.getByText('刷新实时额度 · 排队中', { exact: true }).waitFor()
  await page.getByText('模拟额度服务不可用', { exact: true }).waitFor({ timeout: 10000 })
  check(await page.locator('.ant-notification-notice').last().evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth }), 'Mobile notification overflow')
  await page.screenshot({ path: '/private/tmp/atm-messages-notification.png' })
  await page.goto(`${fixture}?scene=usage&view=quota&interactive=1&stayRunning=1`)
  await page.getByRole('button', { name: '刷新实时额度', exact: true }).click()
  await page.getByText('刷新实时额度 · 排队中', { exact: true }).waitFor()
  await rail.getByRole('link', { name: '消息', exact: true }).click()
  await page.locator('.messages-list .workspace-list-item').first().click()
  await page.getByRole('button', { name: '取消任务', exact: true }).click()
  await page.getByText('刷新实时额度 · 已取消', { exact: true }).first().waitFor()
  check(await page.getByRole('button', { name: '取消任务', exact: true }).count() === 0, 'Completed job retains cancel action')
  return 'PASS: quiet Agent, portal tooltip, hover overlay, cross-page job completion, persistent message history, read status, mobile notifications'
}
